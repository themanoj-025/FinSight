# ------------------------------------------------------ the quality claim (B.1)
@pytest.mark.parametrize("k", [5, 10])
def test_archetype_purity_fraud_neighbors_cluster(env, k):
    """Phase B.1 acceptance: a fraud archetype's transactions retrieve
    neighbors predominantly from the same archetype.

    Measured on the fraud-labeled rows of the returned neighborhood: the
    majority of fraud neighbors must share the query row's archetype, and the
    nearest fraud neighbor must share it too (the strongest form of the
    claim). Legitimate rows in the neighborhood are expected (fraud is ~1% of
    the ledger) and don't count against purity.
    """
    df = env["df"]
    fraud = df[df["isFraud"] == 1]
    counts = fraud["fraud_archetype"].value_counts()
    archetypes = [a for a, n in counts.items() if n >= 4]
    assert archetypes, "fixture should carry several archetypes with support >= 4"

    index, positions = _index(df)
    pos_by_tid = {int(t): int(i) for i, t in enumerate(positions)}

    all_frac: list[float] = []
    nearest_ok = 0
    queries = 0
    for arch in archetypes:
        rows = fraud[fraud["fraud_archetype"] == arch].index
        for tid in rows[:2]:  # up to two queries per archetype
            if tid not in pos_by_tid:
                continue
            pos = pos_by_tid[tid]
            hits = index.find_similar(index.embeddings[pos : pos + 1], k=k, exclude=int(tid))
            fraud_n = [h for h in hits if h.get("fraud_archetype")]
            if not fraud_n:
                continue  # no fraud neighbors in range — nothing to measure
            queries += 1
            frac = sum(1 for h in fraud_n if h["fraud_archetype"] == arch) / len(fraud_n)
            all_frac.append(frac)
            nearest_ok += int(fraud_n[0]["fraud_archetype"] == arch)

    assert queries >= 3, "expected at least 3 measurable queries"
    assert np.mean(all_frac) >= 0.5, (
        f"same-archetype fraction among fraud neighbors too low: "
        f"mean {np.mean(all_frac):.2f} over {queries} queries"
    )
    assert nearest_ok / queries >= 0.6, (
        f"nearest fraud neighbor shares the archetype only {nearest_ok}/{queries} times"
    )

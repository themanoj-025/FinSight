"""Similar-transaction retrieval (Phase B.1) — unit + quality tests.

The quality claim is concrete and checkable: a transaction generated by a
specific fraud archetype should retrieve neighbors predominantly from the same
archetype, because the feature space (strictly backward-looking features,
L2-normalized) is what the generator's fraud patterns shape. We assert it on a
hermetic generated ledger, never on guessed numbers.
"""

